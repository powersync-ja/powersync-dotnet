namespace PowerSync.Common.SourceGenerators;

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

/// <summary>
/// Implements <c>IFromRow&lt;T&gt;</c> for partial types marked with <c>[GenerateSqlMapper]</c>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SqlMapperGenerator : IIncrementalGenerator
{
    internal const string AttributeMetadataName = "PowerSync.Common.DB.GenerateSqlMapperAttribute";

    private static readonly string GeneratorVersion = typeof(SqlMapperGenerator).Assembly.GetName().Version?.ToString() ?? "1.0.0";

    private const string FromRowMetadataName = "PowerSync.Common.DB.IFromRow`1";
    private const string ColumnAttributeMetadataName = "PowerSync.Common.DB.Schema.Attributes.ColumnAttribute";
    private const string IgnoredAttributeMetadataName = "PowerSync.Common.DB.Schema.Attributes.IgnoredAttribute";

    private const string AttributeSource = """
        // <auto-generated/>
        #nullable enable

        namespace PowerSync.Common.DB
        {
            /// <summary>
            /// Generates an <c>IFromRow&lt;T&gt;</c> implementation for the annotated partial type, so it can be
            /// used directly with <c>GetAll&lt;T&gt;</c>, <c>Get&lt;T&gt;</c>, <c>GetOptional&lt;T&gt;</c> and <c>Watch&lt;T&gt;</c>.
            /// </summary>
            /// <remarks>
            /// Each property is read from the column named by its <c>[Column]</c> attribute, or from the column with the
            /// same name as the property (ignoring case). Properties marked with <c>[Ignored]</c> are skipped.
            /// Constructor parameters, such as those of a positional record, are matched to columns in the same way.
            /// Non-nullable members throw if their column is null.
            /// </remarks>
            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct, AllowMultiple = false, Inherited = false)]
            internal sealed class GenerateSqlMapperAttribute : global::System.Attribute
            {
            }
        }

        """;

    private const string EmbeddedAttributeSource = """
        // <auto-generated/>

        namespace Microsoft.CodeAnalysis
        {
            [global::Microsoft.CodeAnalysis.Embedded]
            internal sealed partial class EmbeddedAttribute : global::System.Attribute
            {
            }
        }

        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
        {
            ctx.AddSource("Microsoft.CodeAnalysis.EmbeddedAttribute.g.cs", SourceText.From(EmbeddedAttributeSource, Encoding.UTF8));
            ctx.AddSource("GenerateSqlMapperAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8));
        });

        var results = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeMetadataName,
            predicate: static (node, _) => node is TypeDeclarationSyntax,
            transform: static (ctx, ct) => Transform(ctx, ct));

        context.RegisterSourceOutput(results, static (spc, result) =>
        {
            foreach (var diagnostic in result.Diagnostics)
            {
                spc.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (result.Source is not null)
            {
                spc.AddSource(result.HintName, SourceText.From(result.Source, Encoding.UTF8));
            }
        });
    }

    private sealed record GeneratorResult(string HintName, string? Source, EquatableArray<DiagnosticInfo> Diagnostics);

    private sealed record Member(string Name, ITypeSymbol Type, string Column);

    private static GeneratorResult Transform(GeneratorAttributeSyntaxContext context, CancellationToken ct)
    {
        var type = (INamedTypeSymbol)context.TargetSymbol;
        var syntax = (TypeDeclarationSyntax)context.TargetNode;
        var compilation = context.SemanticModel.Compilation;
        var location = syntax.Identifier.GetLocation();
        var hintName = HintName(type);

        GeneratorResult Fail(params DiagnosticInfo[] diagnostics) =>
            new(hintName, null, new EquatableArray<DiagnosticInfo>(diagnostics.ToImmutableArray()));

        if (compilation.GetTypeByMetadataName(FromRowMetadataName) is null)
        {
            return Fail(DiagnosticInfo.Create(Descriptors.MissingPowerSyncCommon, location));
        }

        for (var current = type; current is not null; current = current.ContainingType)
        {
            if (!IsPartial(current, ct))
            {
                return Fail(DiagnosticInfo.Create(Descriptors.NotPartial, location, current.Name));
            }
        }

        var typeName = type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
        if (type.IsStatic || type.IsAbstract)
        {
            return Fail(DiagnosticInfo.Create(Descriptors.NotConstructible, location, typeName, "the type is static or abstract"));
        }
        if (type.IsRefLikeType)
        {
            return Fail(DiagnosticInfo.Create(Descriptors.NotConstructible, location, typeName, "ref structs cannot implement interfaces"));
        }

        var constructor = SelectConstructor(type, compilation, ct);
        if (constructor is null)
        {
            return Fail(DiagnosticInfo.Create(Descriptors.NotConstructible, location, typeName, "it has no accessible constructor"));
        }

        var columnAttribute = compilation.GetTypeByMetadataName(ColumnAttributeMetadataName);
        var ignoredAttribute = compilation.GetTypeByMetadataName(IgnoredAttributeMetadataName);
        var properties = GetProperties(type);

        var arguments = new List<Member>();
        foreach (var parameter in constructor.Parameters)
        {
            var property = properties.FirstOrDefault(p => string.Equals(p.Name, parameter.Name, StringComparison.OrdinalIgnoreCase));
            var column = property is null ? parameter.Name : ColumnName(property, columnAttribute);
            arguments.Add(new Member(parameter.Name, parameter.Type, column));
        }

        var initializers = new List<Member>();
        foreach (var property in properties)
        {
            if (arguments.Any(a => string.Equals(a.Name, property.Name, StringComparison.OrdinalIgnoreCase))) continue;
            if (HasAttribute(property, ignoredAttribute)) continue;
            if (property.DeclaredAccessibility == Accessibility.Private) continue;
            if (property.SetMethod is null || !compilation.IsSymbolAccessibleWithin(property.SetMethod, type)) continue;

            initializers.Add(new Member(property.Name, property.Type, ColumnName(property, columnAttribute)));
        }

        var diagnostics = new List<DiagnosticInfo>();
        var argumentExpressions = new List<string>();
        var initializerLines = new List<string>();

        foreach (var argument in arguments)
        {
            var expression = ReadExpression(argument.Type, argument.Column, $"__value{argumentExpressions.Count}");
            if (expression is null)
            {
                diagnostics.Add(UnsupportedType(argument, location));
                continue;
            }
            argumentExpressions.Add(expression);
        }

        foreach (var initializer in initializers)
        {
            var expression = ReadExpression(initializer.Type, initializer.Column, $"__value{arguments.Count + initializerLines.Count}");
            if (expression is null)
            {
                diagnostics.Add(UnsupportedType(initializer, location));
                continue;
            }
            initializerLines.Add($"{EscapeIdentifier(initializer.Name)} = {expression},");
        }

        if (diagnostics.Count > 0)
        {
            return Fail(diagnostics.ToArray());
        }

        var source = Emit(type, argumentExpressions, initializerLines);
        return new GeneratorResult(hintName, source, new EquatableArray<DiagnosticInfo>(ImmutableArray<DiagnosticInfo>.Empty));
    }

    private static DiagnosticInfo UnsupportedType(Member member, Location location) =>
        DiagnosticInfo.Create(
            Descriptors.UnsupportedMemberType,
            location,
            member.Name,
            member.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat));

    private static bool IsPartial(INamedTypeSymbol type, CancellationToken ct) =>
        type.DeclaringSyntaxReferences.Any(r =>
            r.GetSyntax(ct) is TypeDeclarationSyntax declaration && declaration.Modifiers.Any(SyntaxKind.PartialKeyword));

    /// <summary>
    /// Prefers a primary constructor (e.g. a positional record), then a parameterless constructor, then the
    /// constructor with the most parameters.
    /// </summary>
    private static IMethodSymbol? SelectConstructor(INamedTypeSymbol type, Compilation compilation, CancellationToken ct)
    {
        var candidates = type.InstanceConstructors
            .Where(c => compilation.IsSymbolAccessibleWithin(c, type))
            .Where(c => !(c.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(c.Parameters[0].Type, type)))
            .ToList();

        return candidates.FirstOrDefault(c => c.DeclaringSyntaxReferences.Any(r => r.GetSyntax(ct) is TypeDeclarationSyntax))
            ?? candidates.FirstOrDefault(c => c.Parameters.Length == 0)
            ?? candidates.OrderByDescending(c => c.Parameters.Length).FirstOrDefault();
    }

    /// <summary>
    /// Instance properties of the type and its base types, base-first, with overridden or hidden properties
    /// replaced by the most derived declaration.
    /// </summary>
    private static List<IPropertySymbol> GetProperties(INamedTypeSymbol type)
    {
        var hierarchy = new List<INamedTypeSymbol>();
        for (var current = type; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
        {
            hierarchy.Insert(0, current);
        }

        var properties = new List<IPropertySymbol>();
        foreach (var declaringType in hierarchy)
        {
            foreach (var property in declaringType.GetMembers().OfType<IPropertySymbol>())
            {
                if (property.IsStatic || property.IsIndexer || property.IsImplicitlyDeclared) continue;

                var index = properties.FindIndex(p => p.Name == property.Name);
                if (index >= 0)
                {
                    properties[index] = property;
                }
                else
                {
                    properties.Add(property);
                }
            }
        }
        return properties;
    }

    private static bool HasAttribute(ISymbol symbol, INamedTypeSymbol? attribute) =>
        attribute is not null && symbol.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, attribute));

    private static string ColumnName(IPropertySymbol property, INamedTypeSymbol? columnAttribute)
    {
        var attribute = columnAttribute is null
            ? null
            : property.GetAttributes().FirstOrDefault(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, columnAttribute));
        if (attribute is null) return property.Name;

        foreach (var named in attribute.NamedArguments)
        {
            if (named.Key == "Name" && named.Value.Value is string name) return name;
        }
        if (attribute.ConstructorArguments.Length > 0 && attribute.ConstructorArguments[0].Value is string ctorName)
        {
            return ctorName;
        }
        return property.Name;
    }

    /// <summary>
    /// Builds the expression that reads <paramref name="column"/> from <c>row</c> as <paramref name="type"/>, or
    /// returns null if the type is not supported.
    /// </summary>
    private static string? ReadExpression(ITypeSymbol type, string column, string temp)
    {
        var literal = SymbolDisplay.FormatLiteral(column, quote: true);
        var nullable = type.NullableAnnotation != NullableAnnotation.NotAnnotated;

        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullableType)
        {
            type = nullableType.TypeArguments[0];
            nullable = true;
        }
        else if (type.IsValueType)
        {
            nullable = false;
        }

        var fullName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string Get(string method) => nullable ? $"row.Get{method}OrNull({literal})" : $"row.Get{method}({literal})";
        string Cast(string method) => nullable ? $"checked(({fullName}?){Get(method)})" : $"checked(({fullName}){Get(method)})";
        string Parse(string parse)
        {
            if (!nullable) return string.Format(parse, $"row.GetString({literal})");
            return $"row.GetStringOrNull({literal}) is {{ }} {temp} ? ({fullName}?){string.Format(parse, temp)} : null";
        }

        if (type.TypeKind == TypeKind.Enum)
        {
            var nullArm = nullable
                ? $"default({fullName}?)"
                : $"throw new global::System.InvalidOperationException({SymbolDisplay.FormatLiteral($"Column '{column}' is null.", true)})";
            return $"row.GetValue({literal}) switch {{ null => {nullArm}, string {temp} => global::System.Enum.Parse<{fullName}>({temp}, true), var {temp} => ({fullName})global::System.Convert.ToInt64({temp}, global::System.Globalization.CultureInfo.InvariantCulture) }}";
        }

        if (type is IArrayTypeSymbol { ElementType.SpecialType: SpecialType.System_Byte })
        {
            return nullable
                ? $"(byte[]?)row.GetValue({literal})"
                : $"(byte[])(row.GetValue({literal}) ?? throw new global::System.InvalidOperationException({SymbolDisplay.FormatLiteral($"Column '{column}' is null.", true)}))";
        }

        switch (type.SpecialType)
        {
            case SpecialType.System_String: return Get("String");
            case SpecialType.System_Boolean: return Get("Bool");
            case SpecialType.System_Int32: return Get("Int");
            case SpecialType.System_Int64: return Get("Long");
            case SpecialType.System_Double: return Get("Double");
            case SpecialType.System_DateTime: return Get("DateTime");
            case SpecialType.System_Single: return nullable ? $"(float?){Get("Double")}" : $"(float){Get("Double")}";
            case SpecialType.System_SByte:
            case SpecialType.System_Byte:
            case SpecialType.System_Int16:
            case SpecialType.System_UInt16:
            case SpecialType.System_UInt32:
            case SpecialType.System_UInt64:
                return Cast("Long");
            case SpecialType.System_Decimal:
                return Parse("global::System.Decimal.Parse({0}, global::System.Globalization.NumberStyles.Float, global::System.Globalization.CultureInfo.InvariantCulture)");
        }

        switch (fullName)
        {
            case "global::System.Guid":
                return Parse("global::System.Guid.Parse({0})");
            case "global::System.DateTimeOffset":
                return Parse("global::System.DateTimeOffset.Parse({0}, global::System.Globalization.CultureInfo.InvariantCulture, global::System.Globalization.DateTimeStyles.AssumeUniversal)");
        }

        return null;
    }

    private static string Emit(INamedTypeSymbol type, List<string> arguments, List<string> initializers)
    {
        var fullName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        var indent = 0;
        void Line(string text) => builder.Append(' ', indent * 4).AppendLine(text);
        void Open(string text)
        {
            Line(text);
            Line("{");
            indent++;
        }
        void Close(string suffix = "")
        {
            indent--;
            Line("}" + suffix);
        }

        var hasNamespace = !type.ContainingNamespace.IsGlobalNamespace;
        if (hasNamespace)
        {
            Open($"namespace {type.ContainingNamespace.ToDisplayString()}");
        }

        var containingTypes = new List<INamedTypeSymbol>();
        for (var current = type.ContainingType; current is not null; current = current.ContainingType)
        {
            containingTypes.Insert(0, current);
        }
        foreach (var containingType in containingTypes)
        {
            Open($"partial {Keyword(containingType)} {DeclarationName(containingType)}");
        }

        Open($"partial {Keyword(type)} {DeclarationName(type)} : global::PowerSync.Common.DB.IFromRow<{fullName}>");
        Line("/// <summary>Creates an instance from a query result row.</summary>");
        Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"PowerSync.Common.SourceGenerators\", \"{GeneratorVersion}\")]");
        Open($"public static {fullName} FromRow(global::PowerSync.Common.DB.IQueryRow row)");

        if (arguments.Count == 0)
        {
            Line(initializers.Count == 0 ? $"return new {fullName}();" : $"return new {fullName}");
        }
        else
        {
            Line($"return new {fullName}(");
            indent++;
            for (var i = 0; i < arguments.Count; i++)
            {
                var last = i == arguments.Count - 1;
                Line(arguments[i] + (!last ? "," : initializers.Count == 0 ? ");" : ")"));
            }
            indent--;
        }

        if (initializers.Count > 0)
        {
            Line("{");
            indent++;
            foreach (var initializer in initializers)
            {
                Line(initializer);
            }
            Close(";");
        }

        Close();
        Close();
        foreach (var _ in containingTypes)
        {
            Close();
        }
        if (hasNamespace)
        {
            Close();
        }

        return builder.ToString();
    }

    private static string Keyword(INamedTypeSymbol type) => type switch
    {
        { IsRecord: true, TypeKind: TypeKind.Struct } => "record struct",
        { IsRecord: true } => "record",
        { TypeKind: TypeKind.Struct } => "struct",
        _ => "class",
    };

    private static string DeclarationName(INamedTypeSymbol type) =>
        type.TypeParameters.Length == 0
            ? EscapeIdentifier(type.Name)
            : $"{EscapeIdentifier(type.Name)}<{string.Join(", ", type.TypeParameters.Select(p => EscapeIdentifier(p.Name)))}>";

    private static string EscapeIdentifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    private static string HintName(INamedTypeSymbol type)
    {
        var name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", "");
        var builder = new StringBuilder(name.Length);
        foreach (var c in name)
        {
            builder.Append(char.IsLetterOrDigit(c) || c == '.' || c == '_' ? c : '_');
        }
        return builder.Append(".SqlMapper.g.cs").ToString();
    }
}
